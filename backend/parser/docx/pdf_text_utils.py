"""Общие примитивы разбора PDF: единицы, нормализация текста и номера страниц.

Модуль не зависит ни от моделей отчета, ни от PyMuPDF: его импортируют и
выравнивание DOCX с PDF (``parser.docx.pdf_page_aligner``), и автономный
PDF-парсер (``parser.pdf``). Благодаря этому сравнение текстов, распознавание
номеров страниц и перевод пунктов в миллиметры описаны в одном месте, а
результаты двух парсеров остаются сопоставимыми.
"""
from __future__ import annotations

import re
from typing import Optional

#: Один пункт PDF в миллиметрах (1 pt = 1/72 дюйма).
PT_TO_MM = 25.4 / 72.0

#: Символы, которыми типографика обрамляет номер страницы: -, ‒, –, —.
PAGE_NUMBER_DASHES = "-\u2012\u2013\u2014"

#: Все не-буквенно-цифровые символы: используются при сжатии строк.
RE_NON_ALNUM = re.compile(r"[^\w]+", re.UNICODE)

#: Номер страницы в колонтитуле: "2", "- 2 -", "Стр. 2", "page 2".
RE_PAGE_NUM_CANDIDATE = re.compile(
    r"^\s*(?:стр\.?|страница|page|p\.?)?\s*[\-\u2012\u2013\u2014]?\s*"
    r"(?P<num>\d{1,4})\s*[\-\u2012\u2013\u2014]?\s*$",
    re.IGNORECASE,
)


def normalize_compact(text: str) -> str:
    """Сжимает строку до буквенно-цифрового потока в нижнем регистре (ё -> е).

    Сжатие делает сравнение нечувствительным к мягким переносам слов, разрывам
    строк и расстановке пробелов в PDF, поэтому по нему сопоставляются абзацы
    DOCX и строки PDF, заголовки и записи оглавления.
    """
    lowered = text.lower().replace("ё", "е")
    return RE_NON_ALNUM.sub("", lowered).replace("_", "")


def parse_page_number(text: str) -> Optional[int]:
    """Возвращает номер страницы из строки колонтитула или None.

    Понимает одиночную цифру, цифру в тире ("- 2 -") и подпись ("Стр. 2").
    Числа длиннее четырех цифр и строки с лишним текстом номером не считаются.
    """
    match = RE_PAGE_NUM_CANDIDATE.match(text.strip())
    if not match:
        return None
    return int(match.group("num"))


def pt_to_mm(value_pt: float) -> float:
    """Переводит пункты PDF в миллиметры с округлением до сотых."""
    return round(value_pt * PT_TO_MM, 2)
