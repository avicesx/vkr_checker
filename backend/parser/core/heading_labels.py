"""Метки служебных страниц ВКР, которые не являются заголовками структуры.

Титульный лист и лист задания набраны служебными реквизитами: название работы
(«ВЫПУСКНАЯ КВАЛИФИКАЦИОННАЯ РАБОТА»), отметка о выполнении («РАБОТА
ВЫПОЛНЕНА»), название листа («ЗАДАНИЕ»). В DOCX эти строки часто оформлены
стилем заголовка (полужирный, по центру, крупный кегль), а в PDF кегль и
начертание вообще единственный признак заголовка, поэтому разбор принимает
реквизит за заголовок. Тогда в дереве документа появляется ложный раздел:
правило уровней требует, чтобы первый заголовок был первого уровня, правило
нумерации — чтобы у раздела был номер, а оглавление сверяется с несуществующим
элементом структуры.

Метка служебной страницы называет работу или лист, а не элемент структуры ВКР
(введение, глава, заключение, список источников, приложение), поэтому заголовок
ей не присваивается ни в DOCX, ни в PDF.

Сравнение идет по началу строки и ограничено формами, которые действительно
встречаются на служебных страницах: «Задание на проектирование АСУ» — обычный
заголовок раздела методички, а «ЗАДАНИЕ НА ВЫПУСКНУЮ КВАЛИФИКАЦИОННУЮ РАБОТУ»
— название листа задания.
"""
from __future__ import annotations

import re

#: Начало строки-метки служебной страницы.
#:
#: * «ВЫПУСКНАЯ КВАЛИФИКАЦИОННАЯ РАБОТА» (возможно «на тему …»);
#: * «РАБОТА ВЫПОЛНЕНА» (возможно «студентом …», «исполнителем …»);
#: * «ЗАДАНИЕ», «ЗАДАНИЕ НА ВЫПУСКНУЮ КВАЛИФИКАЦИОННУЮ РАБОТУ», «ЗАДАНИЕ НА ВКР».
RE_TITLE_PAGE_LABEL = re.compile(
    r"^\s*(?:"
    r"выпускная\s+квалификационная\s+работа(?:\s+на\s+тему\b.*)?"
    r"|работ[аы]\s+выполнен[аы]"
    r"(?:\s+(?:студент\w*|исполнител\w*|автор\w*)\b.*)?"
    r"|задани[ея](?:\s+на\s+(?:"
    r"выпускную\s+квалификационную\s+работу|вкр|дипломн\w*\s+проектирование"
    r"))?"
    r")\s*(?:$|[:.,;(])",
    re.IGNORECASE | re.DOTALL,
)
"""Регулярное выражение метки служебной страницы."""


def is_title_page_label(text: str) -> bool:
    """True, если строка — метка служебной страницы, а не заголовок структуры."""
    return bool(RE_TITLE_PAGE_LABEL.match(text or ""))


__all__ = ["RE_TITLE_PAGE_LABEL", "is_title_page_label"]
