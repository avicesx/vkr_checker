"""Тесты паритета моделей и миграций Alembic.

Каждый тест работает на отдельной временной базе, созданной рядом с
TEST_DATABASE_URL, и удаляет её после проверки: основная тестовая база не
меняется. Без TEST_DATABASE_URL тесты пропускаются.
"""

from __future__ import annotations

import os
import re
from uuid import uuid4

import pytest
from alembic import command
from alembic.script import ScriptDirectory
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import inspect, text
from sqlalchemy.engine import Engine, make_url
from sqlalchemy.exc import ProgrammingError

from app.database import create_database_engine
from app.migrations import apply_migrations, build_alembic_config
from app.models.base import Base

TEST_DATABASE_URL = os.environ.get("TEST_DATABASE_URL")

pytestmark = pytest.mark.skipif(
    not TEST_DATABASE_URL,
    reason="Для тестов миграций задайте TEST_DATABASE_URL PostgreSQL",
)


def _temporary_database_urls(base_url: str) -> tuple[str, str, str]:
    """Возвращает URL временной базы, её имя и URL служебной базы postgres."""
    url = make_url(base_url)
    if not url.database:
        pytest.skip("TEST_DATABASE_URL не содержит имени базы")
    name = f"{url.database}_migr_{uuid4().hex[:8]}"
    if not re.fullmatch(r"[a-z0-9_]+", name):
        pytest.skip("Имя базы из TEST_DATABASE_URL не подходит для временной")
    temporary_url = url.set(database=name).render_as_string(hide_password=False)
    admin_url = url.set(database="postgres").render_as_string(hide_password=False)
    return temporary_url, name, admin_url


@pytest.fixture()
def empty_database_url() -> str:
    """Создаёт пустую временную базу и удаляет её после теста."""
    temporary_url, name, admin_url = _temporary_database_urls(TEST_DATABASE_URL or "")
    admin_engine = create_database_engine(admin_url).execution_options(
        isolation_level="AUTOCOMMIT"
    )
    try:
        try:
            with admin_engine.connect() as connection:
                connection.execute(text(f'CREATE DATABASE "{name}"'))
        except ProgrammingError as exc:
            pytest.skip(f"Нет прав на создание временной базы: {exc}")
        yield temporary_url
    finally:
        with admin_engine.connect() as connection:
            connection.execute(
                text(
                    "SELECT pg_terminate_backend(pid) FROM pg_stat_activity "
                    "WHERE datname = :name AND pid <> pg_backend_pid()"
                ),
                {"name": name},
            )
            connection.execute(text(f'DROP DATABASE IF EXISTS "{name}"'))
        admin_engine.dispose()


def _application_tables(engine: Engine) -> set[str]:
    """Имена таблиц базы без служебной таблицы версий Alembic."""
    return set(inspect(engine).get_table_names()) - {"alembic_version"}


def _check_no_model_drift(database_url: str) -> None:
    """Падает, если autogenerate находит расхождение моделей и миграций."""
    try:
        command.check(build_alembic_config(database_url))
    except AutogenerateDiffsDetected as exc:
        pytest.fail(f"Модели и миграции разошлись: {exc}")


def test_upgrade_head_creates_all_metadata_tables(empty_database_url: str) -> None:
    """upgrade head на пустой базе создаёт ровно таблицы из Base.metadata."""
    engine = create_database_engine(empty_database_url)
    try:
        apply_migrations(engine)
        inspector = inspect(engine)

        assert inspector.has_table("alembic_version")
        assert _application_tables(engine) == set(Base.metadata.tables)

        # Колонки и их nullable совпадают с моделями для каждой таблицы.
        for table_name, table in Base.metadata.tables.items():
            actual_columns = {
                column["name"]: column
                for column in inspector.get_columns(table_name)
            }
            assert set(actual_columns) == {column.name for column in table.columns}
            for column in table.columns:
                assert actual_columns[column.name]["nullable"] == bool(
                    column.nullable
                ), f"{table_name}.{column.name}"

        # Ключевые колонки, которые легко потерять при ручной правке миграции.
        upload_check_columns = {
            column["name"]: column
            for column in inspector.get_columns("upload_check")
        }
        assert upload_check_columns["id"]["nullable"] is False
        assert upload_check_columns["id"]["type"].length == 36
        assert upload_check_columns["created_at"]["type"].timezone is True

        # Ограничения, заданные в __table_args__ и unique=True.
        ruleset_indexes = {
            index["name"]: index for index in inspector.get_indexes("ruleset")
        }
        assert ruleset_indexes["uq_ruleset_active_per_guideline"]["unique"] is True
        assert "uq_ruleset_guideline_version" in {
            constraint["name"]
            for constraint in inspector.get_unique_constraints("ruleset")
        }
        assert any(
            "text_hash" in (constraint.get("column_names") or [])
            for constraint in inspector.get_unique_constraints("guideline")
        )
        assert {
            foreign_key["referred_table"]
            for foreign_key in inspector.get_foreign_keys("violation")
        } == {"check", "rule"}

        with engine.connect() as connection:
            recorded_version = connection.execute(
                text("SELECT version_num FROM alembic_version")
            ).scalar_one()
        head = ScriptDirectory.from_config(
            build_alembic_config(empty_database_url)
        ).get_current_head()
        assert recorded_version == head
    finally:
        engine.dispose()


def test_models_and_migrations_do_not_diverge(empty_database_url: str) -> None:
    """После upgrade head alembic check не находит новых операций."""
    engine = create_database_engine(empty_database_url)
    try:
        apply_migrations(engine)
    finally:
        engine.dispose()

    _check_no_model_drift(empty_database_url)


def test_schema_from_create_all_is_adopted_by_migrations(
    empty_database_url: str,
) -> None:
    """База старого create_all помечается baseline-ревизией без ошибок."""
    engine = create_database_engine(empty_database_url)
    try:
        Base.metadata.create_all(bind=engine)
        assert not inspect(engine).has_table("alembic_version")

        apply_migrations(engine)

        inspector = inspect(engine)
        assert inspector.has_table("alembic_version")
        assert _application_tables(engine) == set(Base.metadata.tables)
    finally:
        engine.dispose()

    _check_no_model_drift(empty_database_url)


def test_incomplete_legacy_schema_is_completed_before_stamp(
    empty_database_url: str,
) -> None:
    """Неполная база create_all досоздаётся, а не помечается актуальной."""
    engine = create_database_engine(empty_database_url)
    try:
        Base.metadata.tables["user"].create(bind=engine)
        assert _application_tables(engine) == {"user"}
        assert not inspect(engine).has_table("alembic_version")

        apply_migrations(engine)

        inspector = inspect(engine)
        assert inspector.has_table("alembic_version")
        assert _application_tables(engine) == set(Base.metadata.tables)
        assert {
            column["name"] for column in inspector.get_columns("user")
        } == {"id", "name", "role"}
    finally:
        engine.dispose()

    _check_no_model_drift(empty_database_url)


def test_legacy_schema_with_missing_column_is_rejected(
    empty_database_url: str,
) -> None:
    """Недостающую колонку create_all не исправит: версия схемы не пишется."""
    engine = create_database_engine(empty_database_url)
    try:
        Base.metadata.create_all(bind=engine)
        with engine.begin() as connection:
            connection.execute(text('ALTER TABLE "user" DROP COLUMN role'))

        with pytest.raises(RuntimeError) as error:
            apply_migrations(engine)

        message = str(error.value)
        assert "user.role" in message
        assert "ручную миграцию" in message
        assert not inspect(engine).has_table("alembic_version")
    finally:
        engine.dispose()


def test_incomplete_legacy_schema_with_missing_column_is_not_stamped(
    empty_database_url: str,
) -> None:
    """Даже после досоздания таблиц неполная колонка блокирует штамп."""
    engine = create_database_engine(empty_database_url)
    try:
        Base.metadata.tables["user"].create(bind=engine)
        with engine.begin() as connection:
            connection.execute(text('ALTER TABLE "user" DROP COLUMN role'))

        with pytest.raises(RuntimeError) as error:
            apply_migrations(engine)

        assert "user.role" in str(error.value)
        # Отсутствующие таблицы досозданы, но актуальной база не объявлена.
        assert _application_tables(engine) == set(Base.metadata.tables)
        assert not inspect(engine).has_table("alembic_version")
    finally:
        engine.dispose()
